"""Render the README Key Results block from results/key_results.json.

    python scripts/render_readme.py          rewrite the block
    python scripts/render_readme.py --check  exit 1 if the README is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"


def block() -> str:
    k = json.loads((ROOT / "results" / "key_results.json").read_text())
    A, smp = k["assets"], k["sample"]
    lines = [
        START,
        f"Sample {smp['start']} to {smp['end']} ({smp['n_days']} return days, "
        f"{smp['high_vol_share']:.0%} classified High-Vol).",
        "",
        "| Asset | Sharpe Low-Vol | Sharpe High-Vol | Sharpe Full | Beta Low-Vol | Beta High-Vol | Change in beta | CVaR95 High / Low | GARCH alpha + beta | VaR IND test p |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for t, a in A.items():
        s, b = a["sharpe"], a.get("beta")
        bl = f"{b['low']:.2f} | {b['high']:.2f} | {b['dbeta_pct']:+.0f}%" if b else "1.00 | 1.00 | (benchmark)"
        lines.append(
            f"| {t} | {s['Low-Vol']:.2f} | {s['High-Vol']:.2f} | {s['Full Sample']:.2f} | {bl} | "
            f"{a['cvar_mult']:.2f}x | {a['garch_persistence']:.3f} ({a['garch_dist']}) | "
            f"{a['var_backtest_full']['p_ind']:.3f} |"
        )
    stocks = {t: a for t, a in A.items() if "beta" in a}
    up = [t for t, a in stocks.items() if a["beta"]["dbeta_pct"] > 0]
    down = [t for t, a in stocks.items() if a["beta"]["dbeta_pct"] <= 0]
    hv = [a["sharpe"]["High-Vol"] for a in A.values()]
    lower = sum(a["sharpe"]["High-Vol"] < a["sharpe"]["Low-Vol"] for a in A.values())
    cm = [a["cvar_mult"] for a in A.values()]
    ind_fail = [t for t, a in A.items() if a["var_backtest_full"]["p_ind"] < 0.05]
    ps = k["portfolio_stress"]
    lines += [
        "",
        f"- Beta rises in High-Vol periods for {', '.join(up) or 'none'}"
        + (f" and falls for {', '.join(down)}" if down else "") + ".",
        f"- High-Vol Sharpe is below Low-Vol Sharpe for {lower} of {len(A)} assets; "
        f"High-Vol Sharpe ranges from {min(hv):.2f} to {max(hv):.2f}.",
        f"- High-Vol CVaR95 is {min(cm):.1f}x to {max(cm):.1f}x Low-Vol CVaR95.",
        f"- Full-sample historical VaR fails the Christoffersen independence test at 5% for "
        f"{', '.join(ind_fail) or 'no asset'} ({len(ind_fail)} of {len(A)}).",
        "- Equal-weight portfolio stress loss: "
        + "; ".join(f"{n} {v:.1%}" for n, v in ps.items()) + ".",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        print("results markers not found in README.md", file=sys.stderr)
        return 1
    new = pat.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        if new != text:
            print("README Key Results block is stale: rerun the notebook and render", file=sys.stderr)
            return 1
        print("README Key Results block matches results/key_results.json")
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
