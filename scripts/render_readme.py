"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"


def headline(m: dict) -> str:
    r, b, g, s = m["market_by_regime"], m["betas"], m["managed"], m["sample"]
    mk = g["Market"]
    hs = mk["hindsight_uncapped_gross"]
    n_beta = sum(v["p_holm"] < 0.05 for v in b.values())
    big = max(b.values(), key=lambda v: abs(v["diff"]))
    checks = {
        "volatility roughly doubles in the High regime": 1.8 < r["vol_ratio"] < 2.5,
        "the mean return does not differ between regimes": abs(r["return_diff"]["t"]) < 1.96,
        "the Sharpe ratio is lower in the High regime": r["high"]["sharpe"] < r["low"]["sharpe"],
        "more than half of the industry betas shift, all by less than 0.2":
            n_beta > len(b) / 2 and abs(big["diff"]) < 0.2,
        "no managed series has a significant alpha after the Holm correction":
            all(v["p_holm"] > 0.05 for v in g.values()),
        "the market's managed alpha is not significant on its own": abs(mk["alpha_t"]) < 1.96,
        "no Sharpe ratio improves significantly": all(v["sharpe_diff"]["lo"] <= 0 for v in g.values()),
        "the hindsight version is significant for the market": hs["alpha_t"] > 1.96,
        "all 13 alphas are positive": all(v["alpha_ann"] > 0 for v in g.values()),
        "real time scaling alone removes significance, capped or not":
            abs(mk["uncapped"]["alpha_t"]) < 1.96 and abs(mk["gross"]["alpha_t"]) < 1.96,
        "management deepens the market's worst drawdown": mk["max_drawdown_managed"] < mk["max_drawdown_unmanaged"],
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    d = mk["sharpe_diff"]
    return (
        f"**Answer, from {s['regime_days']:,} days since {s['regime_first'][:4]}: regimes change risk a great deal, "
        f"and that turns out to be very hard to use.** Market volatility is {r['high']['ann_vol']:.0%} a year in "
        f"the High regime against {r['low']['ann_vol']:.0%} in the Low one, and the regime is known the day "
        f"before. The average return is not detectably different (t = {r['return_diff']['t']:.1f}), so the Sharpe "
        f"ratio is {r['low']['sharpe']:.2f} in calm markets and {r['high']['sharpe']:.2f} in turbulent ones. Betas "
        f"shift for {n_beta} of {len(b)} industries, the largest by {abs(big['diff']):.2f}. Yet scaling "
        f"exposure down when volatility is high, in real time with leverage capped at {s['cap']:.0f}x, adds "
        f"{mk['alpha_ann']:.1%} a year of alpha to the market with t = {mk['alpha_t']:.1f}, moves its Sharpe "
        f"ratio from {mk['sharpe_unmanaged']:.2f} to {mk['sharpe_managed']:.2f} (95% interval for the change "
        f"{d['lo']:+.2f} to {d['hi']:+.2f}), and is significant for none of the 13 series once they are counted. "
        f"The textbook version, with the scaling constant chosen in hindsight and no leverage limit, gives "
        f"t = {hs['alpha_t']:.1f}."
    )


def results(m: dict) -> str:
    r, b, g, s, lab = m["market_by_regime"], m["betas"], m["managed"], m["sample"], m["labels"]
    lo, hi = r["low"], r["high"]
    out = [f"Daily data {s['data_first']} to {s['data_last']}. Regime labels start {s['regime_first']} after a five "
           f"year warm-up; managed portfolios run monthly from {s['managed_first']} to {s['managed_last']} "
           f"({s['managed_months']:,} months).", "",
           "### 1. The market in each regime", "",
           "| Regime | Days | Return per year | Volatility | Sharpe | 99% one day loss | Worst day |",
           "|---|---|---|---|---|---|---|"]
    for name, v in (("Low", lo), ("High", hi)):
        out.append(f"| {name} | {v['days']:,} | {v['ann_return']:+.1%} | {v['ann_vol']:.1%} | {v['sharpe']:.2f} | "
                   f"{v['var_99']:.1%} | {v['worst_day']:.1%} |")
    out += ["", f"High days are {r['share_high']:.0%} of the sample and a spell in one regime lasts "
            f"{r['mean_spell_days']:.0f} trading days on average. Difference in return, High minus Low: "
            f"{r['return_diff']['ann_diff']:+.1%} a year, t = {r['return_diff']['t']:.2f}.", "",
            "### 2. Industry betas in each regime", "",
            "| Industry | Beta, Low | Beta, High | Change | t | p, Holm |", "|---|---|---|---|---|---|"]
    for k, v in sorted(b.items(), key=lambda kv: -kv[1]["diff"]):
        out.append(f"| {lab[k]} | {v['beta_low']:.2f} | {v['beta_high']:.2f} | {v['diff']:+.2f} | {v['t']:+.1f} | "
                   f"{v['p_holm']:.3f} |")
    out += ["", "### 3. Using it: volatility managed portfolios", "",
            f"Real time scaling, leverage capped at {s['cap']:.0f}x, {s['cost_bps']:.0f} bps per unit of change in "
            f"exposure. Alpha is the intercept of the managed series on the unmanaged one.", "",
            "| Series | Alpha per year | t | p, Holm | Sharpe, unmanaged | Sharpe, managed | Change, 95% interval | "
            "Worst drawdown, unmanaged | managed |", "|---|---|---|---|---|---|---|---|---|"]
    for k, v in g.items():
        d = v["sharpe_diff"]
        out.append(f"| {lab[k]} | {v['alpha_ann']:+.1%} | {v['alpha_t']:+.2f} | {v['p_holm']:.2f} | "
                   f"{v['sharpe_unmanaged']:.2f} | {v['sharpe_managed']:.2f} | {d['diff']:+.2f} [{d['lo']:+.2f}, "
                   f"{d['hi']:+.2f}] | {v['max_drawdown_unmanaged']:.0%} | {v['max_drawdown_managed']:.0%} |")
    mk = g["Market"]
    out += ["", f"The managed market holds {mk['mean_weight']:.2f} times the market on average, is at the cap in "
            f"{mk['share_at_cap']:.0%} of months and changes its exposure by {mk['turnover_per_year']:.1f} times "
            f"capital a year.", "",
            "**What each realistic constraint costs, for the market**", "",
            "| Version | Alpha per year | t | Largest exposure |", "|---|---|---|---|",
            f"| Hindsight scaling, no cap, no costs | {mk['hindsight_uncapped_gross']['alpha_ann']:+.1%} | "
            f"{mk['hindsight_uncapped_gross']['alpha_t']:+.2f} | {mk['hindsight_uncapped_gross']['max_weight']:.1f}x |",
            f"| Real time scaling, no cap, with costs | {mk['uncapped']['alpha_ann']:+.1%} | {mk['uncapped']['alpha_t']:+.2f} | "
            f"{mk['uncapped']['max_weight']:.1f}x |",
            f"| Real time scaling, {s['cap']:.0f}x cap, no costs | {mk['gross']['alpha_ann']:+.1%} | {mk['gross']['alpha_t']:+.2f} | "
            f"{mk['gross']['max_weight']:.1f}x |",
            f"| Real time scaling, {s['cap']:.0f}x cap, with costs (reported above) | {mk['alpha_ann']:+.1%} | "
            f"{mk['alpha_t']:+.2f} | {mk['max_weight']:.1f}x |", "",
            "**The managed market by third of the sample**", "",
            "| Period | Alpha per year | t | Sharpe, unmanaged | Sharpe, managed |", "|---|---|---|---|---|"]
    for k, v in m["market_thirds"].items():
        out.append(f"| {k} | {v['alpha_ann']:+.1%} | {v['alpha_t']:+.2f} | {v['sharpe_unmanaged']:.2f} | "
                   f"{v['sharpe_managed']:.2f} |")
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
